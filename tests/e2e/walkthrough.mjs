// 폰 크기로 온보딩부터 주요 화면까지 눌러 보고 스크린샷을 남긴다.
// 사용: node tests/e2e/walkthrough.mjs <앱 URL> <스크린샷 폴더>
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const [url = 'http://localhost:8080/', out = 'shots'] = process.argv.slice(2);
const browser = await chromium.launch();
const errors = [];
const shot = async (p, name) => { await p.waitForTimeout(450); await p.screenshot({ path: `${out}/${name}.png` }); };

const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });
await page.goto(url);
await shot(page, '01-welcome');
await page.click('[data-act="onb-next"]');
await page.fill('#onbAllow', '30000');
await page.click('.days7 button >> nth=1');
await shot(page, '02-allowance');
await page.click('[data-act="onb-next"]');
await page.click('[data-act="fx-name"][data-v="교통카드 충전"]');
await page.fill('#fxAmt', '30000');
await page.click('[data-act="fx-add"]');
await page.click('[data-act="fx-name"][data-v="휴대폰 요금"]');
await page.fill('#fxAmt', '13000');
await page.selectOption('#fxDay', '25');
await page.selectOption('#fxUntil', { index: 6 });
await shot(page, '02a-fixed');
await page.click('[data-act="onb-next"]');
await page.click('[data-act="onb-spend-day"][data-v="2"]');
await shot(page, '02b-spend-days');
await page.click('[data-act="onb-next"]');
await page.fill('#onbGoal', '무선 이어폰');
await page.fill('#onbGoalAmt', '200000');
await shot(page, '03-goal');
await page.fill('#onbGoalDate', '2027-01-15');
await page.dispatchEvent('#onbGoalDate', 'change');
await shot(page, '03b-goal-date');
await page.click('[data-act="onb-plan"][data-k="fast"]');
await page.click('[data-act="onb-next"]');
await shot(page, '04-result');
await page.click('text=돈구리 시작하기');
await shot(page, '05-home-new');

await page.click('[data-act="open-settings"]');
await shot(page, '06-settings');
await page.click('.sheet [data-act="set-apply-save"]').catch(() => {});
await shot(page, '06b-settings-tight');
await page.click('.sheet [data-act="demo-load"]');
await shot(page, '07-home-demo');
await page.click('[data-act="open-worry"]');
await shot(page, '08-worry');
await page.click('[data-act="worry-chip"][data-name="마라탕"]');
await shot(page, '09-judge');
await page.click('[data-act="choose"][data-c="hold"]');
await shot(page, '10-after-hold');
await page.click('[data-act="open-settings"]');
await page.click('.sheet [data-act="demo-next"]');
await page.waitForTimeout(400);
await shot(page, '11-next-day-hold');
await page.click('[data-act="hold"][data-o="skip"]');
await page.waitForTimeout(1800);
await shot(page, '12-tree-grew');
await page.click('[data-act="open-worry"]');
await page.click('[data-act="worry-custom"]');
await page.fill('#worryName', '영화');
for (const k of ['1', '4', '0', '0', '0']) await page.click(`.key[data-k="${k}"]`);
await page.click('[data-act="worry-go"]');
await shot(page, '13-judge-custom');
await page.click('[data-act="choose"][data-c="buy"]');
await page.click('[data-act="open-record"]');
for (const k of ['1', '5', '0', '0']) await page.click(`.key[data-k="${k}"]`);
await page.click('[data-act="save-record"]');
await shot(page, '14-home-after-buy');
await page.click('[data-act="open-income"]');
for (const k of ['1', '0', '0', '0', '0']) await page.click(`.key[data-k="${k}"]`);
await shot(page, '14b-income');
await page.click('[data-act="save-income"]');
await shot(page, '14c-home-after-income');
await page.click('.tab[data-tab="log"]');
await shot(page, '15-log');
await page.click('.tab[data-tab="quiz"]');
await page.click('.choice >> nth=0');
await shot(page, '16-quiz-answer');
await page.click('.tab[data-tab="shop"]');
await shot(page, '17-shop');
await page.click('.goods >> nth=1');
await shot(page, '18-buy');
await page.click('[data-act="close"]');

const desk = await browser.newPage({ viewport: { width: 1280, height: 900 } });
desk.on('pageerror', (e) => errors.push(e.message));
await desk.goto(url);
await desk.click('.demo-panel [data-act="demo-load"]');
await shot(desk, '19-desktop');
await browser.close();
console.log(errors.length ? `ERRORS:\n${errors.join('\n')}` : 'no page errors');
